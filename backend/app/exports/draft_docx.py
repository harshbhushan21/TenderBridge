"""Cited draft response sections and the reasoned no-bid report (python-docx)."""
from __future__ import annotations

import re
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from docx import Document
from docx.enum.text import WD_COLOR_INDEX
from docx.shared import Pt, RGBColor

from backend.app.schemas.assessment import BidAssessment, SectionDraft
from backend.app.schemas.documents import SourceSpan

DISCLAIMER = ("SYNTHETIC DEMO DATA — generated by TenderBridge for human review. "
              "Not submitted to any portal.")
_PLACEHOLDER = re.compile(r"(\[\[[^\]]+\]\]|\{\{[^}]+\}\}|\[PLACEHOLDER[^\]]*\]|\[TBD[^\]]*\])", re.I)


def _val(x: Any) -> str:
    return getattr(x, "value", x) if x is not None else ""


def _banner(doc, text: str, color=RGBColor(0x9C, 0x00, 0x06)) -> None:
    p = doc.add_paragraph()
    r = p.add_run(text)
    r.bold = True
    r.font.color.rgb = color


def _add_markdown_paragraph(doc, line: str, placeholders: list[str]) -> None:
    style = None
    stripped = line.lstrip()
    if stripped.startswith(("- ", "* ")):
        style, line = "List Bullet", stripped[2:]
    elif re.match(r"^\d+\.\s", stripped):
        style, line = "List Number", re.sub(r"^\d+\.\s", "", stripped)
    p = doc.add_paragraph(style=style)
    tokens = _PLACEHOLDER.split(line)
    for tok in tokens:
        if not tok:
            continue
        is_ph = bool(_PLACEHOLDER.fullmatch(tok)) or any(ph and ph in tok for ph in placeholders)
        # simple **bold** handling
        for j, part in enumerate(re.split(r"\*\*", tok)):
            if not part:
                continue
            run = p.add_run(part)
            run.bold = j % 2 == 1
            if is_ph:
                run.font.highlight_color = WD_COLOR_INDEX.YELLOW


def _render_markdown(doc, md: str, placeholders: list[str]) -> None:
    for raw in md.splitlines():
        line = raw.rstrip()
        if not line.strip():
            continue
        m = re.match(r"^(#{1,4})\s+(.*)", line)
        if m:
            doc.add_heading(m.group(2), level=min(len(m.group(1)) + 1, 4))
        else:
            _add_markdown_paragraph(doc, line, placeholders)


def _citation_line(n: int, span: SourceSpan) -> str:
    quote = (span.text_span or "").replace("\n", " ").strip()
    if len(quote) > 160:
        quote = quote[:159] + "…"
    sec = f", {span.section_path}" if span.section_path else ""
    return f"[{n}] {span.short()}{sec}" + (f" — \"{quote}\"" if quote else "")


def write_draft_docx(path: Path | str, *, tender_id: str, version: int, drafts: list[SectionDraft],
                     assessment: BidAssessment | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = Document()
    doc.styles["Normal"].font.size = Pt(10.5)
    doc.add_heading(f"Technical Response — {tender_id}", level=0)
    doc.add_paragraph(f"Tender version: v{version}    Generated: "
                      f"{datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")
    if assessment:
        doc.add_paragraph(f"Bid recommendation: {_val(assessment.recommendation)} "
                          f"(score {assessment.score})")
    _banner(doc, DISCLAIMER)

    for d in drafts:
        doc.add_heading(d.title or d.section_key, level=1)
        meta = f"Section {d.section_key} · revision {d.revision} · status {_val(d.status)}"
        doc.add_paragraph(meta).runs[0].italic = True
        if d.stale:
            _banner(doc, "STALE — this draft was written for a superseded tender version. "
                         "Re-review required before use.")
        _render_markdown(doc, d.body_markdown, d.placeholders)
        if d.placeholders:
            p = doc.add_paragraph()
            r = p.add_run("Missing evidence placeholders: " + "; ".join(d.placeholders))
            r.font.highlight_color = WD_COLOR_INDEX.YELLOW
        spans: list[SourceSpan] = []
        seen: set[tuple] = set()
        for c in d.claims:
            for s in c.citations:
                key = (s.doc_id, s.page, s.text_span[:60])
                if key not in seen:
                    seen.add(key)
                    spans.append(s)
        if spans:
            doc.add_heading("Sources", level=3)
            for i, s in enumerate(spans, start=1):
                para = doc.add_paragraph(_citation_line(i, s))
                para.runs[0].font.size = Pt(8.5)
    doc.save(path)
    return path


def write_no_bid_docx(path: Path | str, *, assessment: BidAssessment, report: dict | None = None) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    report = report or {}
    doc = Document()
    doc.add_heading(f"Bid / No-Bid Report — {assessment.tender_id}", level=0)
    doc.add_paragraph(f"Tender version: v{assessment.tender_version}    Run: {assessment.analysis_run_id}")
    _banner(doc, DISCLAIMER)

    doc.add_heading("Recommendation", level=1)
    p = doc.add_paragraph()
    r = p.add_run(f"{_val(assessment.recommendation)} — weighted score {assessment.score}")
    r.bold = True
    if assessment.hard_gate_failures:
        doc.add_paragraph("A failed mandatory gate overrides the weighted score.")
    if report.get("summary") or assessment.narrative:
        doc.add_paragraph(report.get("summary") or assessment.narrative)

    doc.add_heading("Hard gates", level=1)
    for g in assessment.hard_gates:
        line = f"{'PASS' if g.passed else 'FAIL'} · {g.requirement_id} {g.label}: {g.summary}"
        para = doc.add_paragraph(line, style="List Bullet")
        if not g.passed:
            para.runs[0].bold = True
        for i, ev in enumerate(g.evidence, start=1):
            doc.add_paragraph(_citation_line(i, ev)).runs[0].font.size = Pt(8.5)

    if assessment.criteria:
        doc.add_heading("Score breakdown", level=1)
        t = doc.add_table(rows=1, cols=4)
        t.style = "Light Grid Accent 1"
        for i, h in enumerate(["Criterion", "Weight", "Raw", "Weighted"]):
            t.rows[0].cells[i].text = h
        for c in assessment.criteria:
            cells = t.add_row().cells
            cells[0].text, cells[1].text = c.label or c.key, str(c.weight)
            cells[2].text, cells[3].text = str(c.raw_score), str(c.weighted)

    risks = report.get("risks") or assessment.top_risks
    if risks:
        doc.add_heading("Key risks", level=1)
        for rk in risks:
            doc.add_paragraph(rk if isinstance(rk, str) else rk.get("summary", str(rk)), style="List Bullet")
    if assessment.conditions:
        doc.add_heading("Conditions / open actions", level=1)
        for c in assessment.conditions:
            doc.add_paragraph(c, style="List Bullet")

    doc.add_heading("Human decision", level=1)
    reviewer = report.get("reviewer") or "pending"
    doc.add_paragraph(f"Reviewer: {reviewer}")
    if report.get("decision"):
        doc.add_paragraph(f"Decision: {report['decision']}")
    if report.get("comment"):
        doc.add_paragraph(f"Comment: {report['comment']}")
    doc.save(path)
    return path
