"""Key tender dates as an iCalendar file (effective version)."""
from __future__ import annotations

from datetime import datetime, timedelta, timezone
from pathlib import Path

from backend.app.schemas.requirements import KeyFacts


def _events(kf: KeyFacts) -> list[tuple[str, datetime, list[timedelta]]]:
    out = []
    if kf.submission_deadline:
        out.append(("Bid submission deadline", kf.submission_deadline, [timedelta(days=7), timedelta(days=1)]))
    if kf.prebid_meeting:
        out.append(("Pre-bid meeting", kf.prebid_meeting, [timedelta(days=1)]))
    if kf.bid_opening:
        out.append(("Bid opening", kf.bid_opening, []))
    return out


def _utc(dt: datetime) -> datetime:
    return (dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)).astimezone(timezone.utc)


def _desc(kf: KeyFacts, name: str) -> str:
    src = kf.source_for({"Bid submission deadline": "submission_deadline", "Pre-bid meeting": "prebid_meeting",
                         "Bid opening": "bid_opening"}.get(name, ""))
    parts = [f"Tender {kf.tender_id} version v{kf.tender_version}"]
    if kf.reference_no:
        parts.append(f"Ref {kf.reference_no}")
    if src:
        parts.append(f"Source: {src.short()}")
    parts.append("Generated by TenderBridge (synthetic demo). Dates reflect the effective tender version.")
    return " | ".join(parts)


def _fallback_ics(kf: KeyFacts) -> str:
    def fmt(dt: datetime) -> str:
        return _utc(dt).strftime("%Y%m%dT%H%M%SZ")

    def esc(s: str) -> str:
        return s.replace("\\", "\\\\").replace(";", "\\;").replace(",", "\\,").replace("\n", "\\n")

    now = fmt(datetime.now(timezone.utc))
    lines = ["BEGIN:VCALENDAR", "VERSION:2.0", "PRODID:-//TenderBridge//Key Dates//EN", "CALSCALE:GREGORIAN"]
    for i, (name, dt, alarms) in enumerate(_events(kf)):
        lines += ["BEGIN:VEVENT",
                  f"UID:{kf.tender_id}-v{kf.tender_version}-{i}@tenderbridge",
                  f"DTSTAMP:{now}", f"DTSTART:{fmt(dt)}", f"DTEND:{fmt(dt + timedelta(hours=1))}",
                  f"SUMMARY:{esc(f'{kf.tender_id} v{kf.tender_version}: {name}')}",
                  f"DESCRIPTION:{esc(_desc(kf, name))}"]
        for a in alarms:
            lines += ["BEGIN:VALARM", "ACTION:DISPLAY", f"DESCRIPTION:{esc(name)}",
                      f"TRIGGER:-P{a.days}D", "END:VALARM"]
        lines.append("END:VEVENT")
    lines.append("END:VCALENDAR")
    return "\r\n".join(lines) + "\r\n"


def _ics_lib(kf: KeyFacts) -> str:
    from ics import Calendar, Event  # type: ignore
    from ics.alarm import DisplayAlarm  # type: ignore

    cal = Calendar()
    for i, (name, dt, alarms) in enumerate(_events(kf)):
        e = Event(name=f"{kf.tender_id} v{kf.tender_version}: {name}", begin=_utc(dt),
                  end=_utc(dt) + timedelta(hours=1), description=_desc(kf, name),
                  uid=f"{kf.tender_id}-v{kf.tender_version}-{i}@tenderbridge")
        for a in alarms:
            e.alarms.append(DisplayAlarm(trigger=-a))
        cal.events.add(e)
    return cal.serialize()


def render_ics(kf: KeyFacts) -> str:
    try:
        return _ics_lib(kf)
    except Exception:
        return _fallback_ics(kf)


def write_dates_ics(path: Path | str, key_facts: KeyFacts) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render_ics(key_facts), encoding="utf-8", newline="")
    return path
