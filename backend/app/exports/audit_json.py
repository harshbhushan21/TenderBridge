"""Deterministic audit JSON export."""
from __future__ import annotations

import json
from datetime import date, datetime
from enum import Enum
from pathlib import Path
from typing import Any

from pydantic import BaseModel


def _default(o: Any) -> Any:
    if isinstance(o, BaseModel):
        return o.model_dump(mode="json")
    if isinstance(o, (datetime, date)):
        return o.isoformat()
    if isinstance(o, Enum):
        return o.value
    if isinstance(o, (set, frozenset)):
        return sorted(o, key=str)
    if isinstance(o, Path):
        return str(o)
    return str(o)


def dumps_deterministic(payload: Any) -> str:
    return json.dumps(payload, default=_default, sort_keys=True, indent=2, ensure_ascii=False)


def write_audit_json(path: Path | str, *, tender_id: str, version: int, run_id: str | None,
                     payload: dict) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    doc = {
        "tender_id": tender_id,
        "tender_version": version,
        "analysis_run_id": run_id,
        "synthetic_demo_data": True,
        "notice": "Audit trail generated by TenderBridge. No external submission was performed.",
        **payload,
    }
    path.write_text(dumps_deterministic(doc) + "\n", encoding="utf-8")
    return path
